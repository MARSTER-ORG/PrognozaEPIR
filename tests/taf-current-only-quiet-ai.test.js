'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const validity=require('../taf-validity-v1.js');
const dt=(y,mo,d,h,m=0)=>Date.UTC(y,mo-1,d,h,m);
const expired='TAF EPIR 101100Z 1012/1024 03004KT 0800 FZFG SCT026=';
const info=validity.validity(expired,dt(2026,11,11,9,24));
assert.ok(info);
assert.equal(info.start,dt(2026,11,10,12));
assert.equal(info.end,dt(2026,11,11,0),'24 must mean midnight of the next day');
assert.equal(info.active,false);
assert.equal(validity.current({raw:expired},dt(2026,11,11,9,24),'EPIR'),null);
const active='TAF EPIR 111100Z 1112/1124 11006KT 9999 FEW006 SCT009=';
assert.equal(validity.current({raw:active},dt(2026,11,11,12,20),'EPIR')?.raw,active);
assert.equal(validity.current(active,dt(2026,11,12,0)),null);
assert.equal(validity.current(active,dt(2026,11,11,11,50)),null,'TAF valid only from its start');
assert.equal(validity.current(active,dt(2026,11,11,12,20),'EPBY'),null);
assert.equal(validity.current('TAF AMD EPIR 111215Z 1112/1124 11006KT CAVOK=',dt(2026,11,11,13),'EPIR')!==null,true);
const month='TAF EPIR 312300Z 0100/0112 09004KT CAVOK=';
const m=validity.validity(month,dt(2027,1,1,4));
assert.ok(m);
assert.equal(m.start,dt(2027,1,1,0));
assert.equal(m.end,dt(2027,1,1,12));
assert.equal(m.active,true);
assert.equal(validity.current('TAF EPIR 011100Z 0112/0124 00000KT CAVOK=',dt(2026,12,1,13),'EPIR')!==null,true);
assert.equal(validity.current('METAR EPIR 110900Z AUTO 3700 BR VV002=',dt(2026,11,11,10)),null);
const app=fs.readFileSync(path.join(__dirname,'../taf-app-v25.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../taf.html'),'utf8');
const policy=fs.readFileSync(path.join(__dirname,'../taf-fog-policy.js'),'utf8');
assert.ok(app.includes("Validity.current(item,now,'EPIR')"));
assert.ok(app.includes("Validity.current(item,now,id)"));
assert.ok(app.includes('if(activeResult&&lastTafMeta)await analyzeWithGemini()'));
assert.ok(app.includes('window.PrognozaEPIRTAFLastAIReview'));
assert.ok(html.includes('taf-validity-v1.js?v='));
assert.ok(!html.includes('<h2>TAF AI — Gemini'));
assert.ok(html.includes('id="aiMiniStatus"'));
assert.ok(!html.includes('id="geminiResult"'));
assert.ok(policy.includes("if(selected!=='vnext')return;"));
console.log('TAF current-only archive, midnight/month rollover, quiet Gemini and no unnecessary NEXT UI: PASS');
